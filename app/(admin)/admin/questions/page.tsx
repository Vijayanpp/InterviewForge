import type { Metadata } from "next";
import { createSupabaseServerClient } from "@/lib/supabase/server-client";
import { listAllTechnologiesAdmin } from "@/lib/repositories/technologies.repo";
import { listAllTopicsAdmin } from "@/lib/repositories/topics.repo";
import { listQuestionBankEntries } from "@/lib/repositories/question-bank.repo";
import { QuestionsManager } from "@/components/admin/questions-manager";

export const metadata: Metadata = {
  title: "Question Bank",
};

export default async function AdminQuestionsPage() {
  const supabase = await createSupabaseServerClient();
  const [technologies, topics, questions] = await Promise.all([
    listAllTechnologiesAdmin(supabase),
    listAllTopicsAdmin(supabase),
    listQuestionBankEntries(supabase),
  ]);

  return (
    <div className="space-y-lg">
      <div>
        <h1 className="font-headline-lg text-headline-lg text-foreground">Question Bank</h1>
        <p className="mt-xs text-body-md text-muted-foreground">
          Curate optional reference questions for admins. Live interviews are generated by the AI interviewer — not pulled from this bank.
        </p>
      </div>
      <QuestionsManager technologies={technologies} topics={topics} questions={questions} />
    </div>
  );
}
